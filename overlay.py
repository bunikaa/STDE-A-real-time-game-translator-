"""
Етап 3: оверлей — вікно поверх гри.
Показує текст у вікні, яке завжди зверху і напівпрозоре.
Поки текст захардкоджено — переклад підключимо пізніше.
"""

import tkinter as tk  # вбудована бібліотека для вікон (встановлювати не потрібно)


def show_overlay(text):
    """Створює вікно поверх усього і показує в ньому text."""
    window = tk.Tk()  # створюємо головне вікно

    # --- налаштування вікна ---
    window.overrideredirect(True)         # прибрати рамку і заголовок
    window.attributes("-topmost", True)   # завжди поверх інших вікон
    window.attributes("-alpha", 0.85)     # прозорість: 0 = невидимо, 1 = непрозоро



    window.geometry("800x80+250+600")  # наприклад, вікно 800x80 у точці (250, 600)
    # Формат рядка: "ШИРИНАxВИСОТА+X+Y"
    #   ШИРИНА x ВИСОТА — розмір вікна в пікселях
    #   +X+Y — де лівий верхній кут вікна на екрані (як left/top у REGION)
    # Наприклад "800x80+250+600" — вікно 800x80 у точці (250, 600).



    # --- текст усередині вікна ---
    label = tk.Label(
        window,
        text=text,
        font=("Arial", 20),
        fg="white",   # колір літер
        bg="black",   # колір фону вікна
    )
    label.pack()  # розмістити напис у вікні

    # У вікна немає хрестика (ми прибрали рамку), тому закриваємо по кліку мишкою.
    # Синтаксис із lambda прийми поки на віру — розберемо пізніше.
    window.bind("<Button-1>", lambda event: window.destroy())

    window.mainloop()  # запустити цикл вікна — тримає вікно на екрані


if __name__ == "__main__":

    show_overlay("Привіт з оверлея!")
