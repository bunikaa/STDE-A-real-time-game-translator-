"""
Этап 3: оверлей — окно поверх игры.
Показывает текст в окне, которое всегда сверху и полупрозрачное.
Пока текст захардкожен — перевод подключим позже.
"""

import tkinter as tk  # встроенная библиотека для окон (устанавливать не нужно)


def show_overlay(text):
    """Создаёт окно поверх всего и показывает в нём text."""
    window = tk.Tk()  # создаём главное окно

    # --- настройки окна ---
    window.overrideredirect(True)         # убрать рамку и заголовок
    window.attributes("-topmost", True)   # всегда поверх других окон
    window.attributes("-alpha", 0.85)     # прозрачность: 0 = невидимо, 1 = непрозрачно



    window.geometry("800x80+250+600")  # например, окно 800x80 в точке (250, 600)
    # Формат строки: "ШИРИНАxВЫСОТА+X+Y"
    #   ШИРИНА x ВЫСОТА — размер окна в пикселях
    #   +X+Y — где левый верхний угол окна на экране (как left/top в REGION)
    # Например "800x80+250+600" — окно 800x80 в точке (250, 600).
    


    # --- текст внутри окна ---
    label = tk.Label(
        window,
        text=text,
        font=("Arial", 20),
        fg="white",   # цвет букв
        bg="black",   # цвет фона окна
    )
    label.pack()  # разместить надпись в окне

    # У окна нет крестика (мы убрали рамку), поэтому закрываем по клику мышкой.
    # Синтаксис с lambda прими пока на веру — разберём позже.
    window.bind("<Button-1>", lambda event: window.destroy())

    window.mainloop()  # запустить цикл окна — держит окно на экране


if __name__ == "__main__":
    
    show_overlay("Привет из оверлея!")
