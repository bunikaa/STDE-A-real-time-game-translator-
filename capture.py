"""
Этап 1: захват области экрана.
Делает скриншот заданного прямоугольника и сохраняет в файл capture.png.
"""

import mss  # библиотека для скриншотов, которую мы установили через pip

# Область экрана, которую снимаем.
# Все числа — в пикселях. Начало координат (0, 0) — ЛЕВЫЙ ВЕРХНИЙ угол экрана.
# left/top — где начинается прямоугольник, width/height — его размеры.
# Пока это просто верхняя левая четверть экрана — потом подгоним под окно диалога.
ОБЛАСТЬ = {
    "left": 200,    # отступ слева, в пикселях
    "top": 700,     # отступ сверху
    "width": 1500,   # ширина области
    "height": 300,  # высота области
}


def сделать_скриншот():
    """Снимает заданную область и сохраняет в capture.png."""
    # mss.mss() открывает "сессию" захвата экрана.
    # Конструкция with ... as ... гарантирует, что сессия закроется сама,
    # даже если случится ошибка. Это правильный способ работать с ресурсами.
    with mss.MSS() as sct:
        # grab() снимает нужный прямоугольник и возвращает картинку в памяти
        снимок = sct.grab(ОБЛАСТЬ)

        # сохраняем картинку в файл рядом со скриптом
        mss.tools.to_png(снимок.rgb, снимок.size, output="capture.png")

    print("Готово! Скриншот сохранён в capture.png")


# Эта строка запускает функцию, когда мы стартуем файл напрямую.
# Пока прими на веру — объясню отдельно, это важная идиома Python.
if __name__ == "__main__":
    сделать_скриншот()
