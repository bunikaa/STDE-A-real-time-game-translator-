"""
Етап 1: захоплення області екрана.
Робить скріншот заданого прямокутника й зберігає у файл capture.png.
"""

import mss  # бібліотека для скріншотів, яку ми встановили через pip

# Область екрана для захоплення. Усі числа — у пікселях.
# Початок координат (0, 0) — лівий верхній кут екрана.
# left/top — де починається прямокутник, width/height — його розміри.
REGION = {
    "left": 250,     # відступ зліва
    "top": 700,      # відступ зверху
    "width": 1500,   # ширина області
    "height": 300,   # висота області
}


def capture_screen():
    """Знімає область REGION і зберігає у capture.png."""
    # with гарантує, що сесія захоплення закриється сама, навіть у разі помилки
    with mss.MSS() as sct:
        shot = sct.grab(REGION)  # знімаємо прямокутник, зображення лишається в пам'яті
        mss.tools.to_png(shot.rgb, shot.size, output="capture.png")  # зберігаємо у файл
    print("Готово! Скріншот збережено в capture.png")


# Запускаємо функцію, лише якщо файл стартує напряму (а не імпортується)
if __name__ == "__main__":
    capture_screen()
