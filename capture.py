"""
Этап 1: захват области экрана.
Делает скриншот заданного прямоугольника и сохраняет в файл capture.png.
"""

import mss  # библиотека для скриншотов, которую мы установили через pip

# Область экрана для захвата. Все числа — в пикселях.
# Начало координат (0, 0) — левый верхний угол экрана.
# left/top — где начинается прямоугольник, width/height — его размеры.
REGION = {
    "left": 250,     # отступ слева
    "top": 700,      # отступ сверху
    "width": 1500,   # ширина области
    "height": 300,   # высота области
}


def capture_screen():
    """Снимает область REGION и сохраняет в capture.png."""
    # with гарантирует, что сессия захвата закроется сама, даже при ошибке
    with mss.MSS() as sct:
        shot = sct.grab(REGION)  # снимаем прямоугольник, картинка остаётся в памяти
        mss.tools.to_png(shot.rgb, shot.size, output="capture.png")  # сохраняем в файл
    print("Готово! Скриншот сохранён в capture.png")


# Запускаем функцию, только если файл стартует напрямую (а не импортируется)
if __name__ == "__main__":
    capture_screen()
